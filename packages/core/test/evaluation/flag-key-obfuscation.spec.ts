import { createHash } from 'node:crypto'
import type { FlagValueType } from '@openfeature/core'
import {
  configurationFromString,
  configurationToString,
  type FlagsConfiguration,
  parsePrecomputedConfigurationResponse,
} from '../../src/configuration'
import { evaluatePrecomputedConfiguration } from '../../src/evaluation/precomputed-evaluation'

const salt = '000102030405060708090a0b0c0d0e0f'
const context = { targetingKey: 'athlete-123' }
const assignment = {
  allocationKey: 'allocation-123',
  variationKey: 'variation-456',
  variationType: 'boolean',
  variationValue: true,
  reason: 'TARGETING_MATCH',
  doLog: true,
  serialId: 123,
}
const descriptor = { scheme: 'flag-key-sha256-v1', salt }

// These vectors also run in the Rust edge encoder. Expected digests are not
// generated by the SDK implementation under test.
const vectors = [
  ['new-route-planner', 'a60479237ef2f69175bbe0bd581966d1583766941815dc1d414c883767795190'],
  ['Flag', 'adca75d2141c51b0c0f084c1058edfb8e6e763f91aaf54ca06326d9847bd9586'],
  ['flag', '9817872c144b018abd77e3915bd77e2c27f4f534dccff8ffaca27361e3a5e1ee'],
  [' flag ', 'b1a5f851cc82a3fdf03a461d72a2241584dcf455df1d384e02a937901b3bc80b'],
  ['café', '3bfa8c3c17c1b61035b98ecf14007cdf5cba5ce61a48e8cfb65f8106541892d3'],
  ['cafe\u0301', '1e8b7ec5e8028a1ec96b38dd37f6ccea041c0a90358904af40ac5810c23c8765'],
  ['🚲/旗', '94b611e0d3b26b52f6ad66013d1c72f8a92ea109390049759e75d3c8d3aa4dab'],
  ['a\0b', 'bac134d201be5e7f28fc7019248f0809c2a013b137e866446ee71add2bc344c7'],
  ['', '072d985b427f536ad0a11b2d4c5e0f7e6f0ff6d23e779e082f75599ce3fe3eba'],
]

function response(flags: Record<string, unknown>, encoding: Record<string, unknown> = {}) {
  return { data: { attributes: { createdAt: '2026-09-30T00:00:00Z', format: 'PRECOMPUTED', ...encoding, flags } } }
}

function decode(value: unknown): FlagsConfiguration {
  return configurationFromString(
    JSON.stringify({ version: 1, precomputed: { response: JSON.stringify(value), context } })
  )
}

function hash(key: string, publicSalt = salt): string {
  return createHash('sha256')
    .update('datadog.feature-flags.flag-key.v1\0')
    .update(Buffer.from(publicSalt, 'hex'))
    .update(key)
    .digest('hex')
}

describe('precomputed flag-key obfuscation', () => {
  it.each(vectors)('matches the edge digest for %j', (key, digest) => {
    const plain = decode(response({ [key]: assignment }))
    const encoded = decode(response({ [digest]: assignment }, { obfuscated: true, obfuscation: descriptor }))
    expect(evaluatePrecomputedConfiguration(encoded, 'boolean', key, false, context)).toEqual(
      evaluatePrecomputedConfiguration(plain, 'boolean', key, false, context)
    )
  })

  it.each([
    ['boolean', false, true],
    ['string', 'default', 'visible-value'],
    ['number', -1, 12.5],
    ['object', {}, { visible: ['nested', 42] }],
    ['BOOLEAN', false, true],
    ['STRING', 'default', 'visible-value'],
    ['INTEGER', -1, 42],
    ['NUMERIC', -1, 12.5],
    ['JSON', {}, { visible: ['nested', 42] }],
  ])('preserves the complete %s evaluation result', (variationType, defaultValue, variationValue) => {
    const key = 'flag'
    const flag = { ...assignment, variationType, variationValue }
    const type = typeof defaultValue as FlagValueType
    const plain = decode(response({ [key]: flag }))
    const encoded = decode(response({ [hash(key)]: flag }, { obfuscated: true, obfuscation: descriptor }))
    expect(evaluatePrecomputedConfiguration(encoded, type, key, defaultValue, context)).toEqual(
      evaluatePrecomputedConfiguration(plain, type, key, defaultValue, context)
    )
  })

  it('preserves missing-flag and type-mismatch defaults', () => {
    const plain = decode(response({ flag: assignment }))
    const encoded = decode(response({ [hash('flag')]: assignment }, { obfuscated: true, obfuscation: descriptor }))
    for (const key of ['flag', 'missing']) {
      expect(evaluatePrecomputedConfiguration(encoded, 'string', key, 'default', context)).toEqual(
        evaluatePrecomputedConfiguration(plain, 'string', key, 'default', context)
      )
    }
  })

  it('uses the hashed key for per-flag parse errors', () => {
    const encoded = decode(
      response(
        { [hash('invalid')]: { ...assignment, variationValue: 'not-a-boolean' }, [hash('valid')]: assignment },
        { obfuscated: true, obfuscation: descriptor }
      )
    )
    expect(evaluatePrecomputedConfiguration(encoded, 'boolean', 'invalid', false, context)).toMatchObject({
      value: false,
      errorCode: 'PARSE_ERROR',
    })
    expect(evaluatePrecomputedConfiguration(encoded, 'boolean', 'valid', false, context).value).toBe(true)
  })

  it('preserves the encoding through portable configuration round trips', () => {
    const original = decode(response({ [hash('flag')]: assignment }, { obfuscated: true, obfuscation: descriptor }))
    const restored = configurationFromString(configurationToString(original))
    expect(restored).toEqual(original)
    expect(evaluatePrecomputedConfiguration(restored, 'boolean', 'flag', false, context).value).toBe(true)
    expect(Object.keys(restored.precomputed!.response.data.attributes.flags)).toEqual([hash('flag')])
  })

  it('keeps each response salt scoped to its own assignments', () => {
    for (const publicSalt of [salt, 'f'.repeat(32), salt]) {
      const encoded = decode(
        response(
          { [hash('flag', publicSalt)]: assignment },
          { obfuscated: true, obfuscation: { ...descriptor, salt: publicSalt } }
        )
      )
      expect(evaluatePrecomputedConfiguration(encoded, 'boolean', 'flag', false, context).value).toBe(true)
      expect(
        evaluatePrecomputedConfiguration(encoded, 'boolean', 'flag', false, { targetingKey: 'other' })
      ).toMatchObject({
        errorCode: 'INVALID_CONTEXT',
      })
    }
  })

  it.each([{}, { obfuscated: false }])('keeps legacy payloads unchanged: %j', (encoding) => {
    const plain = decode(response({ flag: assignment }, encoding))
    expect(evaluatePrecomputedConfiguration(plain, 'boolean', 'flag', false, context).value).toBe(true)
  })

  it.each([
    { obfuscated: true },
    { obfuscated: 'true', obfuscation: descriptor },
    { obfuscated: null },
    { obfuscated: false, obfuscation: descriptor },
    { obfuscation: descriptor },
    { obfuscated: true, obfuscation: null },
    { obfuscated: true, obfuscation: [] },
    { obfuscated: true, obfuscation: { ...descriptor, scheme: 'flag-key-sha256-v2' } },
    ...['', '0'.repeat(30), '0'.repeat(34), 'G'.repeat(32), salt.toUpperCase(), salt + '\n', 42].map((salt) => ({
      obfuscated: true,
      obfuscation: { ...descriptor, salt },
    })),
  ])('rejects malformed or unsupported encoding metadata: %j', (encoding) => {
    const payload = response({ flag: assignment }, encoding)
    expect(parsePrecomputedConfigurationResponse(payload)).toHaveProperty('error')
    expect(evaluatePrecomputedConfiguration(decode(payload), 'boolean', 'flag', false, context)).toMatchObject({
      value: false,
      errorCode: 'PARSE_ERROR',
    })
    // Initial configurations and IndexedDB values can bypass the wire parser.
    const direct = { precomputed: { response: payload, context } } as FlagsConfiguration
    expect(evaluatePrecomputedConfiguration(direct, 'boolean', 'flag', false, context)).toMatchObject({
      value: false,
      errorCode: 'PARSE_ERROR',
    })
  })

  it.each(['plaintext-key', 'a'.repeat(63), 'a'.repeat(65), 'A'.repeat(64), 'a'.repeat(64) + '\n'])(
    'rejects a malformed encoded map key: %j',
    (key) => {
      expect(
        parsePrecomputedConfigurationResponse(
          response({ [key]: assignment }, { obfuscated: true, obfuscation: descriptor })
        )
      ).toHaveProperty('error')
    }
  )

  it('never retries a missed hashed lookup as plaintext', () => {
    const digest = hash('flag')
    const encoded = decode(response({ [digest]: assignment }, { obfuscated: true, obfuscation: descriptor }))
    expect(evaluatePrecomputedConfiguration(encoded, 'boolean', digest, false, context)).toMatchObject({
      value: false,
      errorCode: 'FLAG_NOT_FOUND',
    })
  })

  it.each(['\ud800', '\udc00', 'a\ud800b'])('does not alias invalid Unicode to a replacement character: %j', (key) => {
    const encoded = decode(response({ [hash(key)]: assignment }, { obfuscated: true, obfuscation: descriptor }))
    expect(evaluatePrecomputedConfiguration(encoded, 'boolean', key, false, context)).toMatchObject({
      value: false,
      reason: 'ERROR',
    })
  })
})
